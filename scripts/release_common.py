"""Shared fail-closed primitives for Nexus GitHub release artifacts.

This module intentionally has no network access and never trusts an archive
member or an extracted tree until it has been checked against the release
manifest generated by :mod:`build_release`.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path, PurePosixPath
import tempfile
from typing import Any
import zipfile


MANIFEST_NAME = "release-manifest.json"
MANIFEST_SCHEMA = "nexus.release.manifest.v1"


class ReleaseError(RuntimeError):
    """A release artifact or lifecycle invariant was violated."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def safe_member_name(name: str) -> str:
    candidate = PurePosixPath(name)
    if not name or candidate.is_absolute() or ".." in candidate.parts or ":" in candidate.parts[0]:
        raise ReleaseError("release archive contains an unsafe path")
    if candidate.name in {"", "."}:
        raise ReleaseError("release archive contains an unsafe path")
    return candidate.as_posix()


def atomic_json_write(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as handle:
        temporary = Path(handle.name)
        json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
    temporary.replace(path)


def load_manifest(root: Path) -> dict[str, Any]:
    location = root / MANIFEST_NAME
    try:
        payload = json.loads(location.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ReleaseError("release manifest is unavailable or invalid") from exc
    if not isinstance(payload, dict) or payload.get("schema_version") != MANIFEST_SCHEMA:
        raise ReleaseError("release manifest is unavailable or invalid")
    files = payload.get("files")
    if not isinstance(files, dict) or not files:
        raise ReleaseError("release manifest is unavailable or invalid")
    for name, metadata in files.items():
        if not isinstance(name, str) or safe_member_name(name) != name:
            raise ReleaseError("release manifest contains an unsafe path")
        if not isinstance(metadata, dict) or not isinstance(metadata.get("sha256"), str) or not isinstance(metadata.get("size"), int):
            raise ReleaseError("release manifest is unavailable or invalid")
    return payload


def verify_release_tree(root: Path) -> dict[str, Any]:
    """Verify exact files and hashes before the installer mutates local state."""
    root = root.resolve(strict=True)
    if not root.is_dir() or root.is_symlink():
        raise ReleaseError("release root must be a real directory")
    manifest = load_manifest(root)
    expected = set(manifest["files"])
    observed: set[str] = set()
    for path in root.rglob("*"):
        if path.is_dir():
            if path.is_symlink():
                raise ReleaseError("release tree must not contain symlinks")
            continue
        if path.is_symlink():
            raise ReleaseError("release tree must not contain symlinks")
        relative = path.relative_to(root).as_posix()
        # Python may create bytecode beside an extracted release after a host
        # starts it. It is never part of the signed payload and cannot replace
        # a verified source file, so ignore this narrowly-scoped runtime cache.
        if "__pycache__" in path.parts and path.suffix == ".pyc":
            continue
        safe_member_name(relative)
        observed.add(relative)
    if observed != expected | {MANIFEST_NAME}:
        raise ReleaseError("release tree differs from its manifest")
    for name, metadata in manifest["files"].items():
        path = root / name
        if path.stat().st_size != metadata["size"] or sha256_file(path) != metadata["sha256"]:
            raise ReleaseError(f"release integrity check failed for {name}")
    return manifest


def safe_extract(archive_path: Path, destination: Path) -> Path:
    """Extract a one-root release archive without traversal or symlink entries."""
    try:
        with zipfile.ZipFile(archive_path) as archive:
            names = archive.namelist()
            if not names:
                raise ReleaseError("release archive is empty")
            roots: set[str] = set()
            for info in archive.infolist():
                name = safe_member_name(info.filename.rstrip("/")) if not info.is_dir() else info.filename.rstrip("/")
                if name:
                    roots.add(PurePosixPath(name).parts[0])
                # Unix symlink type bits. Windows-created archives use regular files.
                if (info.external_attr >> 16) & 0o170000 == 0o120000:
                    raise ReleaseError("release archive must not contain symlinks")
            if len(roots) != 1:
                raise ReleaseError("release archive must have exactly one top-level directory")
            top = next(iter(roots))
            target = destination / top
            if target.exists():
                raise ReleaseError("release destination already exists")
            destination.mkdir(parents=True, exist_ok=True)
            for info in archive.infolist():
                if info.is_dir():
                    continue
                name = safe_member_name(info.filename)
                output = destination / PurePosixPath(name)
                output.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(info) as source, output.open("xb") as sink:
                    while True:
                        block = source.read(1024 * 1024)
                        if not block:
                            break
                        sink.write(block)
    except (OSError, zipfile.BadZipFile) as exc:
        raise ReleaseError("release archive extraction failed") from exc
    verify_release_tree(target)
    return target
